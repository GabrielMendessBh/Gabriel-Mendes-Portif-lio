  let currentLang = 'pt';
 
  function applyLang(lang){
    currentLang = lang;
    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if(dict[key] !== undefined) el.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if(dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
    });
    const indicator = document.getElementById('amora');
    if(indicator) indicator.textContent = lang;
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
    document.querySelectorAll('.migue').forEach(btn => {
      btn.classList.toggle('manga', btn.getAttribute('data-lang') === lang);
    });
    startTyping();
  }
 
  document.querySelectorAll('.migue').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.getAttribute('data-lang')));
  });
 
  function copyText(text, btn){
    navigator.clipboard.writeText(text).then(() => {
      const original = btn.textContent;
      btn.textContent = translations[currentLang].copied_label;
      setTimeout(() => btn.textContent = original, 1500);
    });
  }
 
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if(entry.isIntersecting){
        entry.target.classList.add('pastel');
      }
    });
  }, { threshold: 0.12 });
 
  document.querySelectorAll('section').forEach(sec => {
    sec.classList.add('kiwi');
    observer.observe(sec);
  });
 
  /* ---------------- TEMA CLARO/ESCURO ---------------- */
  const themeToggle = document.getElementById('sorvete');
  const savedTheme = localStorage.getItem('theme');
  if(savedTheme === 'light'){
    document.documentElement.setAttribute('data-theme', 'light');
  }
  if(themeToggle){
    themeToggle.addEventListener('click', () => {
      const isLight = document.documentElement.getAttribute('data-theme') === 'light';
      if(isLight){
        document.documentElement.removeAttribute('data-theme');
        localStorage.setItem('theme', 'dark');
      } else {
        document.documentElement.setAttribute('data-theme', 'light');
        localStorage.setItem('theme', 'light');
      }
    });
  }
 
  /* ---------------- MÁSCARA DE TELEFONE ---------------- */
  const phoneInput = document.getElementById('coala');
  if(phoneInput){
    phoneInput.addEventListener('input', () => {
      let digits = phoneInput.value.replace(/\D/g, '').slice(0, 11);
      let formatted = digits;
      if(digits.length > 0) formatted = '(' + digits.slice(0, 2);
      if(digits.length >= 3) formatted += ') ' + digits.slice(2, 7);
      if(digits.length >= 8) formatted += '-' + digits.slice(7, 11);
      phoneInput.value = formatted;
    });
  }
 
  /* ---------------- CONTADOR DE CARACTERES ---------------- */
  const msgInput = document.getElementById('abacaxi');
  const msgCount = document.getElementById('churrasquinho');
  if(msgInput && msgCount){
    msgInput.addEventListener('input', () => {
      msgCount.textContent = msgInput.value.length;
    });
  }
 
  /* ---------------- VALIDAÇÃO E ENVIO DO FORMULÁRIO ---------------- */
  const contactForm = document.getElementById('suquinho');
  if(contactForm){
    contactForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const dict = translations[currentLang];
      let valid = true;
 
      const fields = [
        { el: document.getElementById('coxinha'), check: v => v.trim().length > 0, errKey: 'err_required' },
        { el: document.getElementById('coala'), check: v => v.replace(/\D/g, '').length >= 10, errKey: 'err_phone' },
        { el: document.getElementById('mamao'), check: v => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v), errKey: 'err_email' },
        { el: document.getElementById('abacaxi'), check: v => v.trim().length > 0, errKey: 'err_required' }
      ];
 
      fields.forEach(field => {
        const errorEl = contactForm.querySelector(`[data-error-for="${field.el.id}"]`);
        const ok = field.check(field.el.value);
        field.el.classList.toggle('pera', !ok);
        if(errorEl) errorEl.textContent = ok ? '' : dict[field.errKey];
        if(!ok) valid = false;
      });
 
      if(valid){
        openModal();
        contactForm.reset();
        if(msgCount) msgCount.textContent = '0';
      }
    });
  }
 
  /* ---------------- MODAL ---------------- */
  const modalOverlay = document.getElementById('salgadinho');
  function openModal(){
    if(!modalOverlay) return;
    modalOverlay.classList.add('tamandua');
    modalOverlay.setAttribute('aria-hidden', 'false');
  }
  function closeModal(){
    if(!modalOverlay) return;
    modalOverlay.classList.remove('tamandua');
    modalOverlay.setAttribute('aria-hidden', 'true');
  }
  const modalClose = document.getElementById('uepa');
  const modalOk = document.getElementById('fumaca');
  if(modalClose) modalClose.addEventListener('click', closeModal);
  if(modalOk) modalOk.addEventListener('click', closeModal);
  if(modalOverlay){
    modalOverlay.addEventListener('click', (e) => {
      if(e.target === modalOverlay) closeModal();
    });
  }
  document.addEventListener('keydown', (e) => {
    if(e.key === 'Escape') closeModal();
  });
 
  /* ---------------- EFEITO DE DIGITAÇÃO ---------------- */
  const typingEl = document.getElementById('morango');
  let typingTimer = null;
 
  function startTyping(){
    if(!typingEl) return;
    if(typingTimer) clearTimeout(typingTimer);
    const phrases = translations[currentLang].typing_phrases;
    let phraseIndex = 0;
    let charIndex = 0;
    let deleting = false;
 
    function tick(){
      const current = phrases[phraseIndex];
      if(!deleting){
        charIndex++;
        typingEl.textContent = current.slice(0, charIndex);
        if(charIndex === current.length){
          deleting = true;
          typingTimer = setTimeout(tick, 1800);
          return;
        }
      } else {
        charIndex--;
        typingEl.textContent = current.slice(0, charIndex);
        if(charIndex === 0){
          deleting = false;
          phraseIndex = (phraseIndex + 1) % phrases.length;
        }
      }
      typingTimer = setTimeout(tick, deleting ? 35 : 65);
    }
    tick();
  }
 
  startTyping();
 
